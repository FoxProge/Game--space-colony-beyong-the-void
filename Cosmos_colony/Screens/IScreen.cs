namespace Space_colony_game.Screens
{
    /// <summary>
    /// Контракт для экранов игры. Экран управляет собственной логикой жизненного цикла,
    /// обновлением и отрисовкой (включая фоновое изображение).
    /// </summary>
    public interface IScreen
    {
        /// <summary>
        /// Вызывается при переходе на этот экран.
        /// </summary>
        void OnEnter();

        /// <summary>
        /// Вызывается при выходе с этого экрана.
        /// </summary>
        void OnExit();

        /// <summary>
        /// Выполняет обновление состояния экрана (обработка ввода, логика, анимации).
        /// </summary>
        void Update();

        /// <summary>
        /// Выполняет отрисовку содержимого экрана (игровой мир, HUD и т.д.).
        /// </summary>
        void Draw();

        /// <summary>
        /// Отрисовывает фоновое изображение или фон уровня. Вызывается отдельно от основной отрисовки,
        /// чтобы позволить менеджеру экранов или рендеру располагать фон под основным содержимым.
        /// </summary>
        void DrawBgImage();
    }
}
